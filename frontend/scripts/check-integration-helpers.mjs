import assert from "node:assert/strict";
import { QueryClient, isCancelledError } from "@tanstack/react-query";
import { signedInDestination, positiveIdParam } from "../src/utils/managementNavigation.js";
import { clearPrivateData, setSessionAccount, getSessionVersion } from "../src/utils/sessionState.js";
import { formatMoney, normalizeDecimal, validDecimal } from "../src/utils/decimalValues.js";
const a={id:1,vaiTros:["CHU_TRO"]}, b={id:2,vaiTros:["CHU_TRO"]};
assert.equal(signedInDestination(a,"/hoa-don?hopDongId=12"),"/hoa-don?hopDongId=12");
for(const unsafe of ["https://evil.invalid/hoa-don","//evil.invalid/hoa-don","/\\evil.invalid/hoa-don","/api/auth/logout"])
  assert.equal(signedInDestination(a,unsafe),"/dashboard");
assert.equal(signedInDestination(a, "/\\[invalid"), "/dashboard");
assert.equal(signedInDestination({id:3,vaiTros:["NGUOI_THUE"]},"/hoa-don"),"/tai-khoan");
assert.equal(positiveIdParam("2147483647"),"2147483647");
assert.equal(positiveIdParam("2147483648"),"");
assert.equal(positiveIdParam("-1"),"");
assert.ok(validDecimal("9007199254740993",19,0,false));
assert.equal(normalizeDecimal("9.007199254740993e15"),"9007199254740993");
assert.equal(formatMoney("9007199254740993"),new Intl.NumberFormat("vi-VN").format(9007199254740993n)+" đ");
const client=new QueryClient({defaultOptions:{queries:{retry:false}}});
client.setQueryData(["auth","me"],a);
client.setQueryData(["hoa-don",1],["private-a"]);
client.setQueryData(["hoa-don",2],["private-b"]);
await clearPrivateData(client,2);
assert.equal(client.getQueryData(["hoa-don",1]),undefined);
assert.deepEqual(client.getQueryData(["hoa-don",2]),["private-b"]);
assert.deepEqual(client.getQueryData(["auth","me"]),a);
let resolveOld, aborted=false;
const pending=client.fetchQuery({queryKey:["thanh-toan",1],queryFn:({signal})=>{
 signal.addEventListener("abort",()=>{aborted=true;});
 return new Promise(resolve=>{resolveOld=resolve;});
}}).catch(error=>{assert.ok(isCancelledError(error));});
const previousVersion=getSessionVersion();
await setSessionAccount(client,b);
assert.ok(aborted);
assert.ok(getSessionVersion()>previousVersion);
resolveOld(["stale-receipt-a"]);
await pending;
assert.equal(client.getQueryData(["thanh-toan",1]),undefined);
assert.equal(client.getQueryData(["hoa-don",2]),undefined);
assert.deepEqual(client.getQueryData(["auth","me"]),b);
await setSessionAccount(client,null);
assert.equal(client.getQueryData(["auth","me"]),null);
client.clear();
console.log("PASS: safe redirects, IDs, large money, account cache isolation and cancelling stale requests");
